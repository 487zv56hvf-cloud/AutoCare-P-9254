export function t(lang: Lang, key: string, vars?: Record<string, string>): string {
  let s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split(`{${k}}`).join(vars[k]);
    });
  }
  return s;
}

export function formatNumber(lang: Lang, n: number): string {
  try {
    return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US').format(n);
  } catch {
    return String(n);
  }
}

/** Formats a YYYY-MM-DD date for display ("5 Oct 2026" / "٥ أكتوبر ٢٠٢٦"); other text is returned as-is. */
export function formatDate(lang: Lang, ymd: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(ymd);
  if (!m) return ymd;
  const d = new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
  try {
    return d.toLocaleDateString(lang === 'ar' ? 'ar-EG' : 'en-GB', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });
  } catch {
    return ymd;
  }
}
